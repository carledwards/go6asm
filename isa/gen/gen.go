//go:build ignore

// Command gen derives the official NMOS 6502 opcode table by probing
// ca65 itself: it assembles every (mnemonic, addressing-mode) candidate
// with cl65 and reads back the opcode byte. The table is thus verified by
// construction against the ca65 byte-identical contract (DESIGN §6.5),
// not hand-transcribed from memory.
//
// Run from the isa/ directory (via `go generate`):
//
//	go run ./gen -o nmos6502_table.go
//
// Requires cl65 (Homebrew: `brew install cc65`).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
)

// The 56 official NMOS mnemonics.
var mnemonics = []string{
	"ADC", "AND", "ASL", "BCC", "BCS", "BEQ", "BIT", "BMI", "BNE", "BPL",
	"BRK", "BVC", "BVS", "CLC", "CLD", "CLI", "CLV", "CMP", "CPX", "CPY",
	"DEC", "DEX", "DEY", "EOR", "INC", "INX", "INY", "JMP", "JSR", "LDA",
	"LDX", "LDY", "LSR", "NOP", "ORA", "PHA", "PHP", "PLA", "PLP", "ROL",
	"ROR", "RTI", "RTS", "SBC", "SEC", "SED", "SEI", "STA", "STX", "STY",
	"TAX", "TAY", "TSX", "TXA", "TXS", "TYA",
}

// mode is one addressing-mode candidate: the isa.Mode constant name and
// the ca65 operand syntax to probe with (forced z:/a: so zp vs abs is
// unambiguous).
type mode struct {
	name    string
	operand string
}

// Memory/immediate modes probed for ordinary instructions. ca65 force
// prefixes (z:/a:) make zero-page vs absolute unambiguous.
var memModes = []mode{
	{"Immediate", " #$00"},
	{"ZeroPage", " z:$02"},
	{"ZeroPageX", " z:$02,x"},
	{"ZeroPageY", " z:$02,y"},
	{"Absolute", " a:$1234"},
	{"AbsoluteX", " a:$1234,x"},
	{"AbsoluteY", " a:$1234,y"},
	{"Indirect", " ($1234)"},
	{"IndexedIndirect", " ($02,x)"},
	{"IndirectIndexed", " ($02),y"},
}

// branchSet: the only NMOS mnemonics with Relative addressing. A bare
// symbol operand (" rtgt") is otherwise ambiguous with Absolute, so the
// Relative probe is restricted to these.
var branchSet = set("BCC", "BCS", "BEQ", "BMI", "BNE", "BPL", "BVC", "BVS")

// accSet: the only mnemonics with Accumulator addressing. ca65 also
// accepts a bare mnemonic (no operand) as accumulator for these, which
// would collide with the Implied probe, so Implied is skipped for them.
var accSet = set("ASL", "LSR", "ROL", "ROR")

func set(ss ...string) map[string]bool {
	m := map[string]bool{}
	for _, s := range ss {
		m[s] = true
	}
	return m
}

// probeModes returns the (mode,operand) candidates to try for mn,
// structurally gated so each accepted probe maps to exactly one mode.
func probeModes(mn string) []mode {
	if branchSet[mn] {
		return []mode{{"Relative", " rtgt"}}
	}
	var ms []mode
	if accSet[mn] {
		ms = append(ms, mode{"Accumulator", " a"})
	} else {
		ms = append(ms, mode{"Implied", ""})
	}
	return append(ms, memModes...)
}

type entry struct {
	mn, mode string
	op       byte
}

func main() {
	out := flag.String("o", "nmos6502_table.go", "output file")
	flag.Parse()

	tmp, err := os.MkdirTemp("", "go6asm-isagen")
	if err != nil {
		fail(err)
	}
	defer os.RemoveAll(tmp)

	cfg := filepath.Join(tmp, "raw.cfg")
	must(os.WriteFile(cfg,
		[]byte("MEMORY { MAIN: start=$0000, size=$0100, file=%O; }\n"+
			"SEGMENTS { CODE: load=MAIN, type=rw; }\n"), 0o644))

	var entries []entry
	for _, mn := range mnemonics {
		for _, m := range probeModes(mn) {
			if op, ok := probe(tmp, cfg, mn, m.operand); ok {
				entries = append(entries, entry{mn, m.name, op})
			}
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].op < entries[j].op })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by \"go run ./gen\"; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source of truth: ca65 (DESIGN §6.5). %d official NMOS opcodes.\n\n", len(entries))
	fmt.Fprintf(&b, "package isa\n\nvar nmos6502Table = []Encoding{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\te(%q, %s, 0x%02X),\n", e.mn, e.mode, e.op)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	must(os.WriteFile(*out, src, 0o644))
	fmt.Fprintf(os.Stderr, "wrote %s (%d opcodes)\n", *out, len(entries))
}

// probe assembles "<mn><operand>" and returns the leading opcode byte if
// ca65 accepts it.
func probe(dir, cfg, mn, operand string) (byte, bool) {
	srcPath := filepath.Join(dir, "p.s")
	binPath := filepath.Join(dir, "p.bin")
	src := ".segment \"CODE\"\n" + mn + operand + "\nrtgt:\n"
	if err := os.WriteFile(srcPath, []byte(src), 0o644); err != nil {
		fail(err)
	}
	_ = os.Remove(binPath)
	cmd := exec.Command("cl65", "-t", "none", "--cpu", "6502",
		"-C", cfg, "-o", binPath, srcPath)
	if err := cmd.Run(); err != nil {
		return 0, false // illegal (mnemonic,mode) combination
	}
	data, err := os.ReadFile(binPath)
	if err != nil || len(data) == 0 {
		return 0, false
	}
	return data[0], true
}

func must(err error) {
	if err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
